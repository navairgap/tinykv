/* Checksum interoperability fixtures per docs/checksum-golden-vectors.md.
 *
 * Expected checksums come from a table-driven CRC-32/ISO-HDLC built here
 * at runtime — a different implementation than the bitwise loop in
 * src/record_codec.c, so the record-field ordering is testable without
 * calling the parser's own helper. */
#include "tinykv/record.h"
#include <assert.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static uint32_t crc_table[256];

static void crc_table_init(void)
{
    uint32_t index;
    for (index = 0; index < 256; ++index) {
        uint32_t crc = index;
        int bit;
        for (bit = 0; bit < 8; ++bit)
            crc = (crc >> 1) ^ (0xEDB88320u & (0u - (crc & 1u)));
        crc_table[index] = crc;
    }
}

static uint32_t crc32_update_independent(uint32_t crc, const uint8_t *bytes,
                                         size_t length)
{
    size_t i;
    for (i = 0; i < length; ++i)
        crc = crc_table[(crc ^ bytes[i]) & 0xFFu] ^ (crc >> 8);
    return crc;
}

static uint32_t crc32_independent(const uint8_t *bytes, size_t length)
{
    return crc32_update_independent(0xFFFFFFFFu, bytes, length) ^
           0xFFFFFFFFu;
}

/* Checksum input for a record: type, lengths, key, and value bytes —
 * the two ranges [4..12] and [17..end], excluding magic and checksum. */
static uint32_t record_crc_independent(const uint8_t *record,
                                       size_t record_length)
{
    uint32_t crc = 0xFFFFFFFFu;
    crc = crc32_update_independent(crc, record + 4, 9);
    crc = crc32_update_independent(crc, record + TINYKV_RECORD_HEADER_SIZE,
                                   record_length - TINYKV_RECORD_HEADER_SIZE);
    return crc ^ 0xFFFFFFFFu;
}

static void test_independent_algorithm_vector(void)
{
    static const uint8_t input[] = "123456789";
    assert(crc32_independent(input, 9) == 0xCBF43926u);
}

static void test_pinned_put_fixture(void)
{
    /* PUT "k" -> "v", pinned bytes generated by the v1 encoder. */
    static const uint8_t fixture[] = {
        0x54, 0x4B, 0x56, 0x31, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
        0x00, 0x01, 0x32, 0xD3, 0x69, 0xCA, 0x6B, 0x76
    };
    tinykv_record_view view;
    size_t consumed = 0;
    uint8_t checksum_input[11];
    uint32_t expected;
    assert(sizeof(fixture) == TINYKV_RECORD_HEADER_SIZE + 2);
    /* Decode the pinned bytes. */
    assert(tinykv_record_decode(fixture, sizeof(fixture), 64, 64, &view,
                                &consumed) == TINYKV_RECORD_OK);
    assert(consumed == sizeof(fixture));
    assert(view.type == TINYKV_RECORD_PUT && view.key_length == 1 &&
           view.value_length == 1);
    assert(view.key[0] == 'k' && view.value[0] == 'v');
    /* Recompute with the independent implementation: type+lengths+payload. */
    memcpy(checksum_input, fixture + 4, 9);
    memcpy(checksum_input + 9, fixture + TINYKV_RECORD_HEADER_SIZE, 2);
    expected = crc32_independent(checksum_input, sizeof(checksum_input));
    assert(((uint32_t)fixture[13] << 24 | (uint32_t)fixture[14] << 16 |
            (uint32_t)fixture[15] << 8 | (uint32_t)fixture[16]) == expected);
    assert(expected == 0x32D369CAu);
}

static void test_encoder_matches_independent_crc(void)
{
    /* Cases from the doc: empty value, non-empty value, delete, opaque
     * bytes, and the smallest (zero-length) key. */
    static const uint8_t opaque_key[] = {0xFF, 0x00, 0x80};
    static const uint8_t opaque_value[] = {0xDE, 0xAD, 0xBE, 0xEF};
    struct {
        uint8_t type;
        const uint8_t *key;
        size_t klen;
        const uint8_t *value;
        size_t vlen;
        const char *description;
    } cases[] = {
        {TINYKV_RECORD_PUT, (const uint8_t *)"key", 3, NULL, 0,
         "put with empty value"},
        {TINYKV_RECORD_PUT, (const uint8_t *)"key", 3,
         (const uint8_t *)"value", 5, "put with non-empty value"},
        {TINYKV_RECORD_DELETE, (const uint8_t *)"gone", 4, NULL, 0,
         "delete with empty value"},
        {TINYKV_RECORD_PUT, opaque_key, 3, opaque_value, 4,
         "non-ASCII opaque bytes"},
        {TINYKV_RECORD_PUT, NULL, 0, (const uint8_t *)"v", 1,
         "zero-length key"},
    };
    size_t c;
    for (c = 0; c < sizeof(cases) / sizeof(cases[0]); ++c) {
        uint8_t *record = NULL;
        size_t length = 0, consumed = 0;
        tinykv_record_view view;
        uint32_t expected, stored;
        assert(tinykv_record_encode(cases[c].type, cases[c].key,
                                    cases[c].klen, cases[c].value,
                                    cases[c].vlen, 64, 64, &record,
                                    &length) == TINYKV_RECORD_OK);
        assert(length == TINYKV_RECORD_HEADER_SIZE + cases[c].klen +
                             cases[c].vlen);
        stored = ((uint32_t)record[13] << 24) | ((uint32_t)record[14] << 16) |
                 ((uint32_t)record[15] << 8) | (uint32_t)record[16];
        /* Independent CRC over type, lengths, key, and value bytes. */
        expected = record_crc_independent(record, length);
        assert(stored == expected);
        assert(tinykv_record_decode(record, length, 64, 64, &view,
                                    &consumed) == TINYKV_RECORD_OK);
        assert(consumed == length);
        assert(view.type == cases[c].type);
        assert(view.key_length == cases[c].klen &&
               view.value_length == cases[c].vlen);
        if (cases[c].klen != 0)
            assert(memcmp(view.key, cases[c].key, cases[c].klen) == 0);
        if (cases[c].vlen != 0)
            assert(memcmp(view.value, cases[c].value, cases[c].vlen) == 0);
        free(record);
    }
}

static void test_rejects_wrong_checksum_variants(void)
{
    /* Start from the pinned valid fixture and mutate the checksum field
     * in every way a broken implementation might. */
    static const uint8_t good[] = {
        0x54, 0x4B, 0x56, 0x31, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
        0x00, 0x01, 0x32, 0xD3, 0x69, 0xCA, 0x6B, 0x76
    };
    uint8_t bad[sizeof(good)];
    tinykv_record_view view;
    size_t consumed = 0;

    /* One-bit change to the checksum input: flip a payload bit. */
    memcpy(bad, good, sizeof(bad));
    bad[18] ^= 0x01;
    assert(tinykv_record_decode(bad, sizeof(bad), 64, 64, &view,
                                &consumed) == TINYKV_RECORD_BAD_CHECKSUM);

    /* Byte-order reversal of the stored checksum. */
    memcpy(bad, good, sizeof(bad));
    bad[13] = good[16];
    bad[14] = good[15];
    bad[15] = good[14];
    bad[16] = good[13];
    assert(tinykv_record_decode(bad, sizeof(bad), 64, 64, &view,
                                &consumed) == TINYKV_RECORD_BAD_CHECKSUM);

    /* A checksum computed over the magic and fields (magic included). */
    memcpy(bad, good, sizeof(bad));
    {
        uint32_t wrong = crc32_independent(bad, 13); /* magic + fields */
        bad[13] = (uint8_t)(wrong >> 24);
        bad[14] = (uint8_t)(wrong >> 16);
        bad[15] = (uint8_t)(wrong >> 8);
        bad[16] = (uint8_t)wrong;
    }
    assert(tinykv_record_decode(bad, sizeof(bad), 64, 64, &view,
                                &consumed) == TINYKV_RECORD_BAD_CHECKSUM);

    /* A checksum that accidentally includes the checksum field. */
    memcpy(bad, good, sizeof(bad));
    {
        uint8_t extended[21];
        uint32_t wrong;
        memcpy(extended, good + 4, 13);   /* fields + checksum field */
        memcpy(extended + 13, good + 17, 2); /* payload */
        wrong = crc32_independent(extended, sizeof(extended));
        bad[13] = (uint8_t)(wrong >> 24);
        bad[14] = (uint8_t)(wrong >> 16);
        bad[15] = (uint8_t)(wrong >> 8);
        bad[16] = (uint8_t)wrong;
    }
    assert(tinykv_record_decode(bad, sizeof(bad), 64, 64, &view,
                                &consumed) == TINYKV_RECORD_BAD_CHECKSUM);
}

int main(void)
{
    crc_table_init();
    test_independent_algorithm_vector();
    test_pinned_put_fixture();
    test_encoder_matches_independent_crc();
    test_rejects_wrong_checksum_variants();
    puts("tinykv golden vectors: all tests passed");
    return 0;
}
